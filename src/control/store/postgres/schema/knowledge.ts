/**
 * Migration 1's tables of the knowledge base, on PostgreSQL (index.ts): its collections, items
 * and versions, its files and their text, what each campaign and run reads, and the rules that
 * keep a version as it was written.
 */
export const KNOWLEDGE_TABLES = `
-- One collection for each campaign, made with the campaign.
create table kb_collection (
  campaign text primary key,
  made_at text not null
);

-- seq: the seq in control's events table of the last event indexed from it, before the apply of
-- the events stream fed the knowledge base (it no longer moves); item_seq: the last seq given to
-- an item's version.
create table kb_cursor (
  id bigint primary key check (id = 1),
  seq bigint not null,
  item_seq bigint not null
);

-- The files control holds, each once by its SHA-256, in its state (control/kb/files.ts).
create table kb_file (
  sha256 text primary key,
  bytes bigint not null,
  stored_at text not null
);

-- Each stored file's text, read out of it for search.
create table kb_file_text (
  sha256 text primary key,
  state text not null check (state in ('searched', 'whole')),
  "text" text not null default '',
  why text,
  chars bigint not null default 0,
  pages bigint,
  extracted_at text not null
);

-- The knowledge base's items, each as its newest version, with its outcome and the context
-- Thermite writes for it.
create table kb_item (
  id bigint generated by default as identity primary key,
  seq bigint not null,
  campaign text not null,
  rig text not null,
  ledger text not null,
  run text not null,
  slot text not null,
  kind text not null,
  ref text not null,
  version bigint not null,
  title text not null,
  body text not null,
  by text not null,
  url text,
  sub text,
  meta text not null default '{}',
  file_sha256 text,
  file_name text,
  file_type text,
  file_bytes bigint,
  at text not null,
  updated_at text not null,
  outcome text,
  context text not null default '',
  unique (rig, ledger, run, slot, kind, ref)
);
create index kb_item_campaign on kb_item (campaign, kind);
create index kb_item_file on kb_item (file_sha256) where file_sha256 is not null;
create index kb_item_outcome on kb_item (campaign, outcome) where outcome is not null;
create index kb_item_seq on kb_item (campaign, seq);

-- A version's links to other items, by their addresses (core/kb/items.ts): supports, contradicts,
-- follows. A link names an address as its writer gave it, found or not.
create table kb_link (
  item bigint not null,
  version bigint not null,
  rel text not null,
  target text not null,
  primary key (item, version, rel, target)
);
create index kb_link_target on kb_link (target);

-- What the items were read with: the reading's version (see READING).
create table kb_meta (
  key text primary key,
  value text not null
);

-- The passages of each item's text, as the words index reads them (goal 269 builds the index).
create table kb_passage (
  id bigint generated by default as identity primary key,
  item bigint not null,
  n bigint not null,
  start bigint not null,
  len bigint not null
);
create index kb_passage_item on kb_passage (item, n);

-- The grants: each campaign that may read another's collection, read only.
create table kb_read (
  campaign text not null,
  reads text not null,
  granted_by text not null,
  granted_at text not null,
  primary key (campaign, reads)
);

-- The campaign of each run that wrote an item.
create table kb_run (
  rig text not null,
  ledger text not null,
  run text not null,
  campaign text not null,
  primary key (rig, ledger, run)
);

-- What a run reads (goal 175, step 4): its campaign's whole collection, or its own run alone when
-- it starts fresh, and the granted collections it includes (JSON). No row: the whole collection
-- and every grant.
create table kb_scope (
  campaign text not null,
  run text not null,
  fresh bigint not null check (fresh in (0, 1)),
  granted text not null default '[]',
  set_by text not null,
  set_at text not null,
  primary key (campaign, run)
);

-- The knowledge base's settings on control, as the owner sets them; no row: its default.
create table kb_setting (
  key text primary key,
  value double precision not null,
  set_by text not null,
  set_at text not null
);

-- Every version of every item, the newest too. None is ever changed or removed.
create table kb_version (
  item bigint not null,
  version bigint not null,
  title text not null,
  body text not null,
  by text not null,
  url text,
  sub text,
  meta text not null default '{}',
  file_sha256 text,
  file_name text,
  file_type text,
  file_bytes bigint,
  event bigint,
  at text not null,
  primary key (item, version)
);
create index kb_version_file on kb_version (file_sha256) where file_sha256 is not null;

-- A version of an item is never changed, and an item's newest version is never removed: a
-- retention policy may remove the older ones.
create function kb_version_never_changed() returns trigger language plpgsql as $fn$
begin
  raise exception 'a version of an item is never changed';
end $fn$;
create trigger kb_version_never_changed before update on kb_version
  for each row execute function kb_version_never_changed();
create function kb_version_newest_kept() returns trigger language plpgsql as $fn$
begin
  if old.version = (select version from kb_item where id = old.item) then
    raise exception 'the newest version of an item is never removed';
  end if;
  return old;
end $fn$;
create trigger kb_version_newest_kept before delete on kb_version
  for each row execute function kb_version_newest_kept();

-- The knowledge base's one row of counters: the place of its newest item.
insert into kb_cursor (id, seq, item_seq) values (1, 0, 0);

`;
