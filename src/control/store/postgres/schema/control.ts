/**
 * Migration 1's tables of control itself, on PostgreSQL (index.ts): its audit log, its settings
 * and sessions, the campaigns, the model providers and their usage, the MCP servers, the retention
 * policies and the bus's keys and places.
 */
export const CONTROL_TABLES = `
-- The audit log: who did what on control, and when. The same entry again counts up in its row.
create table audit (
  id bigint generated by default as identity primary key,
  at text not null,
  actor text not null,
  action text not null,
  body text not null,
  count bigint not null default 1,
  last_at text,
  repeat text
);
create unique index audit_repeat on audit (actor, action, repeat);

-- The keys of control's own users on the message bus, each seed sealed with control's secret box.
create table bus_identity (
  name text primary key check (name in ('control', 'system')),
  public_key text not null,
  seed_sealed text not null,
  created_at text not null
);

-- How far the store applied each of the bus's streams: the place of the last message applied.
create table bus_position (
  stream text primary key,
  seq bigint not null
);

-- Archived campaigns (goal 077): out of the left navigation, Needs you and the Overview's
-- lists. Their runs, results and kits stay; unarchiving removes the row.
create table campaign_archived (
  campaign text primary key,
  archived_at text not null,
  archived_by text not null
);

-- Folders for campaigns in the dashboard's left navigation (goal 077): a name the owner gives,
-- unique whatever its case. They group campaigns there and nowhere else: they are not the
-- campaigns' folders in the knowledge base.
create table campaign_folder (
  id bigint generated by default as identity primary key,
  name text not null,
  created_at text not null,
  created_by text not null
);
create unique index campaign_folder_name on campaign_folder (lower(name));

-- The folder a campaign shows in (goal 077). A campaign in no folder has no row.
create table campaign_in_folder (
  campaign text primary key,
  folder bigint not null references campaign_folder (id)
);

-- Changes the operator proposes to a campaign's settings, for the owner to approve or decline.
create table campaign_proposal (
  id bigint generated by default as identity primary key,
  campaign text not null,
  field text not null check (field in ('role_additions', 'kb_writes', 'kb_grant')),
  value text,
  proposed_by text not null,
  proposed_at text not null,
  decision text check (decision in ('approved', 'declined', 'replaced')),
  decided_by text,
  decided_at text
);

-- Campaigns created on control (the new-campaign page): each version's contract as approved,
-- with its content hash. Runs are assigned from a version.
create table campaign_version (
  campaign text not null,
  version bigint not null,
  contract text not null,
  sha text not null,
  sources text not null default '{}',
  created_at text not null,
  created_by text not null,
  approved_by text,
  copied_from text,
  primary key (campaign, version)
);

-- Control's own builds, each from when it first ran: a rig's page says since when the two differ.
create table control_build (
  -- The order the builds were noted in, as SQLite's own row number of this name is.
  rowid bigint generated always as identity,
  version text not null,
  commit_sha text,
  since text not null
);

-- Control's own settings the owner sets on control.
create table control_setting (
  key text primary key,
  value text not null,
  set_by text not null,
  set_at text not null
);

-- Git access for private repositories (Settings): an SSH deploy key control made (its public
-- half shown, its private half sealed) or an HTTPS token (sealed). Rigs get one only for a
-- campaign assigned to them that names it.
create table git_access (
  name text primary key,
  kind text not null check (kind in ('ssh', 'token')),
  public_key text,
  fingerprint text,
  secret_sealed text not null,
  hint text not null,
  username text,
  created_at text not null,
  created_by text not null,
  host text
);

-- The agents' model usage (goal 075): each model_call event a rig reported, as its columns, kept
-- with the event's key (a ledger a rig left keeps its records), and its run's campaign from the
-- rig's run_created event. What the usage sums read. A figure the harness did not report is null.
create table model_call (
  rig text not null,
  ledger_id text not null,
  event_id bigint not null,
  run text not null,
  campaign text,
  trial text,
  round text,
  agent text not null,
  harness text not null,
  provider text,
  model text not null,
  calls bigint,
  at text not null,
  tokens_in bigint not null,
  cached_in bigint,
  tokens_out bigint not null,
  reasoning bigint,
  first_token_ms bigint,
  call_ms bigint,
  cache_write_in bigint,
  primary key (rig, ledger_id, event_id)
);
create index model_call_at on model_call (at);
create index model_call_campaign on model_call (campaign, at);
create index model_call_run on model_call (run, at);

-- A model's price the owner set (goal 075), in US dollars per million tokens, for a provider's
-- model whose list gives none. cached_input null: the input price.
create table model_price (
  provider text not null,
  model text not null,
  input double precision not null,
  cached_input double precision,
  output double precision not null,
  set_by text not null,
  set_at text not null,
  cache_write double precision,
  primary key (provider, model)
);

-- A model provider the owner set: its type, where it is, and its API key sealed (control's secret
-- box; never stored in clear). models is its own model list, as control last read it (plus any the
-- owner added by name). version moves on every change, so the rigs that use it pick it up.
create table model_provider (
  name text primary key,
  type text not null,
  base_url text not null,
  key_sealed text not null,
  key_hint text not null,
  version bigint not null default 1,
  updated_at text not null,
  models text not null default '[]',
  models_at text,
  models_error text
);

-- A GPU cloud pod's spend as control counts it while it follows the pod (goal 075): each count's
-- spend since the one before, with the run its rig was running then (null: none) and that run's
-- campaign. A spend counted while the rig ran two runs is split evenly between them.
create table pod_spend (
  id bigint generated by default as identity primary key,
  rig text not null,
  run text,
  campaign text,
  at text not null,
  usd double precision not null
);
create index pod_spend_campaign on pod_spend (campaign, at);
create index pod_spend_run on pod_spend (run, at);

-- The addresses cluster rigs' harnesses may reach beside the internet, set by the owner.
create table reachable_address (
  address text primary key,
  ports text not null,
  note text not null default '',
  set_at text not null,
  set_by text not null
);

-- The owner's retention policies.
create table retention_policy (
  id bigint generated by default as identity primary key,
  name text not null,
  kind text not null,
  spec text not null,
  enabled bigint not null default 0,
  on_since text,
  last_due text,
  created_at text not null,
  created_by text not null,
  updated_at text not null,
  updated_by text not null
);

-- What each run of a retention policy removed.
create table retention_removal (
  id bigint generated by default as identity primary key,
  at text not null,
  policy bigint not null,
  name text not null,
  kind text not null,
  rig text,
  by text not null,
  count bigint not null,
  bytes bigint not null,
  oldest text,
  newest text,
  error text
);
create index retention_removal_policy on retention_removal (policy, id);

-- Dashboard sign-ins, kept across restarts. Only a hash of each session id is stored, with a
-- fingerprint of the admin token it was made with (a new token ends every session).
create table ui_session (
  id_hash text primary key,
  token_fp text not null,
  created_at text not null,
  expires_at bigint not null
);
-- MCP servers (goal 068): the server, how it signs Thermite in (its secrets sealed with control's
-- secret box), its state, its last error and its tools as last read.
create table mcp_server (
  name text primary key,
  url text not null,
  auth text not null,
  header text,
  client_id text,
  scope text,
  secret_sealed text,
  secret_hint text,
  login_sealed text,
  status text not null default 'unchecked',
  last_error text,
  tools text,
  tools_at text,
  checked_at text,
  migrated_from text,
  created_at text not null,
  created_by text not null,
  updated_at text not null
);

-- OAuth sign-ins started and not finished yet: their state (hashed), the PKCE verifier (sealed).
create table mcp_sign_in (
  state_hash text primary key,
  name text not null,
  verifier_sealed text not null,
  redirect_uri text not null,
  expires_at text not null,
  started_by text not null
);
`;
