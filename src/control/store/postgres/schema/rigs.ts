/**
 * Migration 1's tables of the rigs, on PostgreSQL (index.ts): the rigs as they report and as
 * control set them up, their commands, runs, exports and live lines.
 */
export const RIG_TABLES = `
-- Champions' patches as each rig's supervisor uploaded them, kept only when they match the
-- sha256 the rig's signed champion_published event names: what an operator downloads.
create table champion_patch (
  rig text not null,
  ledger_id text not null,
  run text not null,
  seq bigint not null,
  sha256 text not null,
  base_commit text not null,
  patch bytea not null,
  received_at text not null,
  primary key (rig, ledger_id, run, seq)
);

-- Kubernetes clusters control sets rigs up on: the kubeconfig sealed, the context, how rigs are
-- placed (namespaces control creates, or slots the cluster's operators made), what the last check
-- found.
create table cluster (
  name text primary key,
  kubeconfig_sealed text not null,
  context text not null default '',
  placement text not null check (placement in ('created', 'slot')),
  namespace_pattern text not null default 'thermite-{rig}',
  slots text not null default '[]',
  facts text,
  checked_at text,
  check_error text,
  created_at text not null,
  created_by text not null,
  unchecked text
);

-- Rigs control set up on a cluster: where, how, and how it stands.
create table cluster_rig (
  rig text primary key,
  cluster text not null,
  namespace text not null,
  placement text not null,
  spec text not null,
  status text not null,
  created_at text not null,
  created_by text not null,
  pending text
);

-- The commands control issued to its rigs, as signed, each with its outcome as the rig gave it.
create table command (
  id text primary key,
  -- The order the commands were issued in: two of the same millisecond stay in their order.
  -- SQLite gives every row such a number under this name, so the statements are the same.
  rowid bigint generated always as identity,
  rig text not null,
  kind text not null,
  signed text not null,
  issued_by text not null,
  issued_at text not null,
  status text not null check (status in ('pending', 'delivered', 'rejected', 'failed', 'expired')),
  outcome text,
  acked_at text,
  run text,
  campaign text
);
create index command_campaign on command (campaign);
create index command_pending on command (rig, status);
create index command_run on command (run);

-- Each rig ledger's floor in control's copy of its events: the last event a retention policy
-- removed on purpose, and the stream's place before which it purged.
create table event_floor (
  rig text not null,
  ledger text not null,
  through_event bigint not null,
  before_place bigint not null,
  at text not null,
  primary key (rig, ledger)
);

-- GPU clouds (RunPod) control reads with the owner's key, sealed: what the last read found.
create table gpu_cloud (
  name text primary key,
  kind text not null check (kind in ('runpod')),
  key_sealed text not null,
  key_hint text not null,
  facts text,
  checked_at text,
  check_error text,
  created_at text not null,
  created_by text not null
);

-- Rigs the owner joins themself (join.ts): where, and the join command's hash, expiry and use.
create table joined_rig (
  rig text primary key,
  form text not null check (form in ('machine', 'namespace')),
  spec text not null,
  join_sha256 text,
  join_expires_at text,
  join_used_at text,
  status text not null,
  created_at text not null,
  created_by text not null
);

-- Machines control sets rigs up on, over SSH: the key sealed, the host keys the owner trusted
-- (none until then), and what the last read-only check found.
create table machine (
  name text primary key,
  address text not null,
  port bigint not null,
  "user" text not null,
  key_sealed text not null,
  public_key text not null,
  key_fingerprint text not null,
  host_keys text not null default '[]',
  seen_host_keys text not null default '[]',
  facts text,
  checked_at text,
  check_error text,
  created_at text not null,
  created_by text not null
);

-- Installs on a machine: each one approved by the owner for one recipe's exact script, used
-- once, before it expires; then its outcome.
create table machine_install (
  id bigint generated by default as identity primary key,
  machine text not null,
  recipe text not null,
  script_sha text not null,
  approved_by text not null,
  approved_at text not null,
  expires_at text not null,
  started_at text,
  finished_at text,
  ok bigint,
  output text
);

-- Rigs control set up on a machine: where, on which GPUs, with which images, and how it stands.
create table machine_rig (
  rig text primary key,
  machine text not null,
  gpus text not null default '[]',
  images text not null,
  root bigint not null default 0,
  status text not null,
  created_at text not null,
  created_by text not null,
  judge_gpus bigint,
  judge_on_runners bigint not null default 0
);

-- Full resets (owner only): pause, export, verify the push, wipe, restart. One open per rig.
create table reset (
  id bigint generated by default as identity primary key,
  rig text not null,
  state text not null,
  requested_by text not null,
  command text,
  export_name text,
  through_event bigint,
  detail text,
  created_at text not null,
  updated_at text not null
);

-- The rigs as they report: when, from which ledger, their summary and their report-signing keys.
create table rig (
  id text primary key,
  first_seen text not null,
  last_seen text not null,
  ledger_id text,
  summary text not null default '{}',
  pubkey text,
  pending_pubkey text,
  report_at text,
  supervisor text,
  supervisor_at text
);

-- The build each part of a rig last reported (the harness in its signed report, the supervisor
-- in its calls' headers), and since when. No row: the part reported none (a build before versions).
create table rig_build (
  rig text not null,
  component text not null check (component in ('harness', 'supervisor')),
  version text,
  commit_sha text,
  protocol bigint,
  oldest_protocol bigint,
  since text not null,
  primary key (rig, component)
);

-- The key each rig registered for the message bus: its public part, and the key results are
-- sealed to.
create table rig_bus_key (
  rig text primary key,
  public_key text not null,
  registered_at text not null,
  seal_key text
);

-- Exports a rig's supervisor sent to control because the rig has no results repository: each
-- export's manifest, the files it sends with their sizes and SHA-256 (from the manifest), which
-- of them arrived and matched, and when the last one did. The files are on disk (exports.ts).
create table rig_export (
  rig text not null,
  name text not null,
  manifest text not null,
  files text not null,
  done text not null default '[]',
  bytes bigint not null,
  "full" bigint not null default 0,
  from_event bigint not null,
  through_event bigint not null,
  created_at text not null,
  complete_at text,
  primary key (rig, name)
);

-- Every ledger a rig has reported from; a ledger it has left is never accepted again.
create table rig_ledger (
  rig text not null,
  ledger_id text not null,
  first_seen text not null,
  superseded_at text,
  through_event bigint not null default 0,
  primary key (rig, ledger_id)
);

-- The live view: recent live-log lines per rig (harness lines signed; supervisor lines not).
create table rig_live (
  id bigint generated by default as identity primary key,
  rig text not null,
  log_id text not null,
  seq bigint not null,
  at text not null,
  source text not null,
  kind text not null,
  "text" text not null,
  lane text,
  run text,
  signed bigint not null,
  received_at text not null
);
create index rig_live_rig on rig_live (rig, id);
create unique index rig_live_seq on rig_live (rig, log_id, seq);
create index rig_live_source on rig_live (rig, source, id);

-- The provider and model each rig's agents use. A rig with none keeps its own settings.
create table rig_model (
  rig text primary key,
  provider text not null,
  model text not null,
  assigned_at text not null,
  harness text not null default 'pi',
  effort text,
  context_cap bigint,
  compact_at bigint
);

-- Rigs control refuses now because their protocol and control's do not meet, and why; how many
-- of the rig's calls control refused since, and when the last one came.
create table rig_refusal (
  rig text primary key,
  reason text not null,
  since text not null,
  calls bigint not null default 0,
  last_at text
);

-- What rigs reported beside their events, by kind.
create table rig_report (
  id bigint generated by default as identity primary key,
  rig text not null,
  kind text not null,
  body text not null,
  at text not null
);

-- Rigs the owner retired: they leave the lists and Needs you, and their reports are refused,
-- until brought back. Their records stay.
create table rig_retired (
  rig text primary key,
  at text not null,
  by text not null
);

-- The model of each of a rig's other agents (the planner; the teachers' first and second model and
-- their merged by model; the auditor; the review panel), when the owner gave one; a role with none
-- follows the workers, or the rig default.
create table rig_role_model (
  rig text not null,
  role text not null check (role in ('planner', 'teachers', 'second_teacher', 'merged_by', 'auditor', 'review_panel', 'synthesizer', 'final_writer')),
  provider text not null,
  model text not null,
  effort text,
  assigned_at text not null,
  harness text,
  context_cap bigint,
  compact_at bigint,
  primary key (rig, role)
);

-- The runner processes control set up for its rigs (goal 206).
create table rig_runner (
  rig text not null,
  runner text not null,
  token_sha256 text,
  cluster text not null,
  namespace text not null,
  placement text not null,
  spec text not null,
  status text not null,
  created_at text not null,
  created_by text not null,
  primary key (rig, runner)
);

-- Each step of setting a rig up or managing it, for the rig's history: what, whether it worked.
create table rig_setup_event (
  id bigint generated by default as identity primary key,
  rig text not null,
  at text not null,
  step text not null,
  ok bigint not null,
  detail text
);

-- Each rig's space as it last reported it.
create table rig_space (
  rig text primary key,
  read_at text not null,
  received_at text not null,
  space text not null
);

-- Rigs enrolled through control (thermite rig add, or the API): each token only as its SHA-256.
-- A rig in the rig tokens file needs no row. A retired rig's token stops working.
create table rig_token (
  rig text primary key,
  token_sha256 text not null,
  created_at text not null,
  created_by text not null,
  rotated_at text,
  retired_at text
);

-- The updates to control's version under way (goal 165): their step and the runs they paused.
create table rig_update (
  rig text primary key,
  phase text not null,
  paused text not null default '[]',
  requested_by text not null,
  started_at text not null,
  updated_at text not null
);

-- A rig's Workers as the owner chose them, until the rig takes them (goal 206).
create table rig_workers (
  rig text primary key,
  lanes bigint not null,
  chosen_by text not null,
  chosen_at text not null,
  given text
);

-- Every run control knows, by rig: its campaign and the command that assigned it.
create table run_registry (
  run text not null,
  rig text not null,
  campaign text,
  command text,
  assigned_at text,
  ledger_id text,
  created_at text,
  primary key (run, rig)
);

-- The key each runner process of a rig registered (goal 206): its public part, by rig and runner.
create table runner_bus_key (
  rig text not null,
  runner text not null,
  public_key text not null,
  registered_at text not null,
  primary key (rig, runner)
);

-- How a rig's runners spent their time (goal 231), as sampled.
create table runner_use (
  rig text not null,
  at text not null,
  body text not null,
  primary key (rig, at)
);

-- Rigs the owner launched on a GPU cloud: the pod, what it was launched with, its price, what
-- control has seen it cost so far, and the owner's spend limit and idle stop, if set.
create table runpod_rig (
  rig text primary key,
  cloud text not null,
  pod text not null,
  active bigint not null,
  state text not null,
  created_at text not null,
  created_by text not null
);

-- Test pods control started on a GPU cloud: what was asked, the pod, and what it found.
create table runpod_test (
  id text primary key,
  cloud text not null,
  active bigint not null,
  state text not null,
  created_at text not null,
  created_by text not null
);

-- A stuck trial the owner left running from its Needs you card (goal 143): by trial and kind
-- (quiet or repeating), since when it was stuck then. A new quiet spell or streak asks again.
create table trial_left (
  rig text not null,
  trial text not null,
  kind text not null,
  since text not null,
  at text not null,
  by text not null,
  primary key (rig, trial, kind)
);

-- Rigs in pull mode, which control connects to through a public proxy (a RunPod pod): the pod
-- once launched, the tunnel's sealed secrets, the one-time enrollment code (spent: ''), the
-- rig's settings, and the pod's keys once enrolled (docs/plan/goals/_completed/019-rig-only-entry.goal).
create table tunnel_rig (
  rig text primary key,
  pod text,
  url text,
  port bigint not null,
  prefix_sealed text not null,
  box_private_sealed text not null,
  box_public text not null,
  code_sealed text not null,
  code_expires_at text,
  config text not null,
  pod_sign_public text,
  pod_box_public text,
  enrolled_at text,
  last_exchange_at text,
  refused_total bigint not null default 0,
  error text,
  created_at text not null,
  created_by text not null,
  leaf_ca text,
  leaf_address text,
  leaf_address_at text
);
`;
