import type { CoreActionName, InputOf, OutputOf, PluginActionBinding } from "../api/index.ts";
import type { DeviceInfo, DomainEvent, RunMode, Verdict } from "../machine/index.ts";
import type { PolicyGrant } from "../policy/index.ts";
import type { HarnessPlugin } from "./harness.ts";
import type { KbPluginHooks } from "./kb.ts";
import type { WallPlugin } from "./wall.ts";

export type { DeviceInfo };

type P<X> = Promise<X>;
type R<X> = Readonly<X>;
type Row = Record<string, unknown>;
type StrMap = R<Record<string, string>>;
type NumMap = R<Record<string, number>>;
type Strs = readonly string[];
type IdVer = R<{ id: string; version: string }>;
type Cleanup = () => void | P<void>;
type Rq1 = { method: string; path: string; headers: StrMap; query: StrMap };
type RouteReq = Rq1 & { body?: unknown; signal: AbortSignal };
type RouteRes = { status: number; headers?: StrMap; body?: unknown };
type Bytes = string | Uint8Array;
type Sock1 = { send(d: Bytes): void; close(code?: number, reason?: string): void };
type Sock = Sock1 & { onMessage(cb: (d: Bytes) => void): void; onClose(cb: () => void): void };
type SockReq = { path: string; headers: StrMap; signal: AbortSignal };
type Ms1 = { jobId: string; deviceIds: Strs; workDir: string };
type MeasSpec = Ms1 & { command: Strs; timeoutMs?: number };
type MeasRes = { ok: boolean; metrics?: NumMap; exitCode?: number | null };
type Alloc = { deviceIds: Strs; env: StrMap; release(): P<void> };
type Drain = { drained: boolean; detail?: string };
type Target = { id: string; label: string; kind: string; available: boolean };
type Prov = { targetId: string; label?: string; image?: string };
type Inst = { instanceId: string; targetId: string; status: string };
type Dep = { name: string; version: string; needs: R<Row>; api: Row | null };
type Sec = { get(k: string): P<string | null> } & { set(k: string, v: string | null): P<void> };
type Ev<K> = K extends "*" ? DomainEvent : Extract<DomainEvent, { type: K }>;
type EvFn<K> = (ev: Ev<K>) => void | P<void>;
export type PluginSql = {
  <T extends Row = Row>(strings: TemplateStringsArray, ...values: readonly unknown[]): P<T[]>;
  begin?<T>(fn: (tx: PluginSql) => P<T>): P<T>;
  unsafe?<T extends Row = Row>(query: string, params?: readonly unknown[]): P<T[]>;
};
type Dev1 = { probe(): P<readonly DeviceInfo[]>; allocate(ids: Strs, jobId: string): P<Alloc> };
type Dev2 = { checkDrained(ids: Strs): P<Drain>; measure(s: MeasSpec, g: AbortSignal): P<MeasRes> };
export type DevicePlugin = IdVer & Dev1 & Dev2;
type Comp1 = { discover(): P<readonly Target[]>; provision(spec: Prov): P<Inst> };
type Comp2 = { enroll(id: string, tok: string, u: string): P<{ machineId: string }> };
export type ComputePlugin = IdVer & Comp1 & Comp2 & { terminate(id: string): P<void> };
type Cal1 = { ok: boolean; judgePlugin: string; judgeVersion: string; sampleCount: number };
export type JudgeCalibrationReport = Cal1 & { falsePositiveRate?: number; detail?: string };
type Ev1 = { runId: string; attemptId: string; mode: RunMode };
type Ev2 = { baselineMetrics?: NumMap; candidateMetrics?: NumMap; rejudgeOf?: string };
export type JudgeEvalContext = Ev1 & Ev2;
type JudgeOut = { verdict: Verdict; judgePlugin: string; judgeVersion: string };
type J1 = { calibrateAA(): P<JudgeCalibrationReport> };
export type JudgePlugin = IdVer & J1 & { evaluate(ctx: JudgeEvalContext): P<JudgeOut> };
export type PluginRoute = (req: RouteReq) => RouteRes | P<RouteRes>;
export type PluginSocketHandler = (ws: Sock, req: SockReq) => void | P<void>;
type SetupRet = void | Cleanup | P<void> | P<Cleanup | undefined>;
export type PluginSetup = (t: PluginApi) => SetupRet;
type Call = <K extends CoreActionName>(n: K, i: InputOf<K>, g?: PolicyGrant) => P<OutputOf<K>>;
type A1 = R<{ name: string; settings: StrMap; sql: PluginSql; secrets: Sec }>;
type A2 = R<{ localUrl: string; signal: AbortSignal; kb: KbPluginHooks }>;
type A3 = { log(...p: unknown[]): void; provide(api: Row): void };
type A4 = { need<T = Row>(name: string): T | null; dependents(): readonly Dep[] };
type A5 = { onEvent<K extends DomainEvent["type"] | "*">(f: K, fn: EvFn<K>): void };
type A6 = { registerActions(a: readonly PluginActionBinding[]): void; callAction: Call };
type A7 = { route(m: string, p: string, h: PluginRoute): void };
type A8 = { socket(p: string, h: PluginSocketHandler): void; registerJudge(j: JudgePlugin): void };
type A9 = { registerHarness(h: HarnessPlugin): void; registerDevice(d: DevicePlugin): void };
type A10 = { registerCompute(c: ComputePlugin): void; registerWall(w: WallPlugin): void };
type ApiCore = A1 & A2 & A3 & A4 & A5;
export type PluginApi = ApiCore & A6 & A7 & A8 & A9 & A10;
