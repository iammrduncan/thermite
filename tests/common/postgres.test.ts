import assert from "node:assert/strict";
import { describe, test } from "node:test";
import { jsonPart, jsonText, numbered, Sql } from "../../src/common/postgres.ts";
import { postgresConnection } from "../helpers/postgres.ts";

/**
 * Thermite's PostgreSQL connection and how a store runs its statements on it (goal 268): the
 * statements are written as SQLite's are, and a transaction is whole.
 */

describe("a statement written with ? for its values", () => {
  test("takes $1, $2 and so on in their place, and a ? inside quotes stays", () => {
    assert.equal(numbered("select 1"), "select 1");
    assert.equal(
      numbered("update t set a = ?, b = ? where c = ?"),
      "update t set a = $1, b = $2 where c = $3",
    );
    assert.equal(
      numbered(`select '?' as q, "a?b" from t where x = ? and y = 'it''s ?' and z = ?`),
      `select '?' as q, "a?b" from t where x = $1 and y = 'it''s ?' and z = $2`,
    );
  });

  test("a field of a JSON text column is read as SQLite's json_extract reads it", async () => {
    const q = new Sql(postgresConnection());
    await q.exec("create table j (body text not null)");
    await q.run(
      "insert into j (body) values (?)",
      JSON.stringify({ a: { b: "deep", n: 7, list: [1, { x: 2 }], none: null } }),
    );
    const row = await q.get(
      `select ${jsonText("body", "a", "b")} as b, ${jsonText("body", "a", "n")} as n,
         ${jsonText("body", "a", "none")} as none, ${jsonText("body", "a", "gone")} as gone,
         ${jsonPart("body", "a", "list")} as list, ${jsonPart("body", "a", "gone")} as no_part
       from j`,
    );
    assert.deepEqual(
      { ...row },
      { b: "deep", n: "7", none: null, gone: null, list: '[1,{"x":2}]', no_part: null },
    );
  });
});

describe("statements on a connection", () => {
  test("give rows with numbers as numbers, how many rows a write changed, and a new row's key", async () => {
    const q = new Sql(postgresConnection());
    await q.exec(
      "create table n (id bigint generated by default as identity primary key, v bigint, t text, b bytea)",
    );
    assert.equal(await q.insert("insert into n (v, t) values (?, ?)", 2 ** 40, "a"), 1);
    assert.equal(
      await q.insert("insert into n (v, t, b) values (?, ?, ?)", 5, "b", Buffer.from("xy")),
      2,
    );
    assert.deepEqual((await q.run("update n set t = t || '!' where v > ?", 0)).changes, 2);
    const rows = await q.all("select id, v, t from n order by id");
    assert.deepEqual(
      rows.map((r) => ({ ...r })),
      [
        { id: 1, v: 2 ** 40, t: "a!" },
        { id: 2, v: 5, t: "b!" },
      ],
    );
    const sums = await q.get("select count(*) as rows, sum(v) as total, avg(v) as mean from n");
    assert.equal(sums?.rows, 2);
    assert.equal(sums?.total, 2 ** 40 + 5, "a sum of whole numbers is a number");
    assert.equal(typeof sums?.mean, "number");
    assert.equal(
      Buffer.from((await q.get("select b from n where id = 2"))?.b as Uint8Array).toString(),
      "xy",
    );
    assert.equal(await q.get("select 1 from n where id = 9"), undefined);
  });

  test("a text with a NUL character is kept with the symbol for it, and nothing is null", async () => {
    const q = new Sql(postgresConnection());
    await q.exec("create table t (a text, b text)");
    await q.run("insert into t (a, b) values (?, ?)", "de\u0000bug", undefined);
    assert.deepEqual({ ...(await q.get("select a, b from t")) }, { a: "de␀bug", b: null });
  });

  test("a transaction keeps all of its statements or none, and one inside it is dropped alone", async () => {
    const q = new Sql(postgresConnection());
    await q.exec("create table t (k text primary key)");
    const keys = async () => (await q.all("select k from t order by k")).map((r) => r.k);
    assert.equal(
      await q.tx(async () => {
        await q.run("insert into t (k) values ('a')");
        return "kept";
      }),
      "kept",
    );
    await assert.rejects(
      q.tx(async () => {
        await q.run("insert into t (k) values ('b')");
        throw new Error("dropped");
      }),
      /dropped/,
    );
    assert.deepEqual(await keys(), ["a"]);
    await q.tx(async () => {
      await q.run("insert into t (k) values ('c')");
      await assert.rejects(
        q.tx(async () => {
          await q.run("insert into t (k) values ('d')");
          // A statement the server refuses: the savepoint is dropped, and the outer one goes on.
          await q.run("insert into t (k) values ('a')");
        }),
        /duplicate key/,
      );
      await q.tx(async () => {
        await q.run("insert into t (k) values ('e')");
      });
    });
    assert.deepEqual(await keys(), ["a", "c", "e"]);
  });
});
